/// Displays a self-contained webmap HTML file (generated by WebMapGenerator)
/// via a file:// URI in a WebView. Includes a Share button to export the
/// .html file so it can be opened in a real browser.
class WebmapViewerScreen extends StatefulWidget {
  final File htmlFile;
  final AppDatabase? database;
  final int? projectId;

  const WebmapViewerScreen(
      {required this.htmlFile, this.database, this.projectId, super.key});

  @override
  State<WebmapViewerScreen> createState() => _WebmapViewerScreenState();
}

class _WebmapViewerScreenState extends State<WebmapViewerScreen> {
  late final WebViewController _controller;
  bool _loading = true;
  late File _file = widget.htmlFile;
  String _projectName = "";
  late int? _projectId = widget.projectId;
  Future<void> _onLayersMessage(JavaScriptMessage message) async {
    if (message.message == 'manage') {
      await _manageLayers();
      return;
    }
    final db = widget.database, id = _projectId;
    if (db == null || id == null) return;
    try {
      final change = jsonDecode(message.message) as Map;
      if (change['action'] != 'visibility' || change['visible'] is! bool) {
        return;
      }
      final service = ProjectVectorLayerService(db),
          layers = await service.load(id);
      for (final layer in layers) {
        if (layer['id'] == change['id']) layer['visible'] = change['visible'];
      }
      await service.save(id, layers);
    } catch (error) {
      debugPrint('Cannot save layer visibility: $error');
    }
  }

  Future<void> _manageLayers() async {
    final db = widget.database, id = _projectId;
    if (db == null || id == null) return;
    await Navigator.of(context).push(MaterialPageRoute(
        builder: (_) =>
            ProjectVectorLayersScreen(database: db, projectId: id)));
    if (!mounted) return;
    setState(() => _loading = true);
    try {
      final generator = WebMapGenerator(
          dataService: WebMapDataService(db, studyAreaStore: StudyAreaStore()));
      _file = await generator
          .writeToFile(await generator.generateHtml(projectId: id));
      await _controller.loadFile(_file.path);
    } catch (error) {
      if (mounted) {
        setState(() => _loading = false);
        ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text("Cannot reload layers: $error")));
      }
    }
  }

  Future<void> _openStudio() async {
    try {
      await _controller.runJavaScript(
          "if (typeof openMapStudio === 'function') openMapStudio();");
    } catch (error) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Cannot open map styles: $error')));
      }
    }
  }

  @override
  void initState() {
    super.initState();
    _controller = WebViewController()
      ..setJavaScriptMode(JavaScriptMode.unrestricted)
      ..setBackgroundColor(Colors.white)
      ..enableZoom(true)
      ..addJavaScriptChannel('MapBanaiExport', onMessageReceived: _exportData)
      ..addJavaScriptChannel('MapBanaiLayers',
          onMessageReceived: _onLayersMessage)
      ..setNavigationDelegate(
        NavigationDelegate(
          onNavigationRequest: (request) => request.url.startsWith('file://')
              ? NavigationDecision.navigate
              : NavigationDecision.prevent,
          onPageFinished: (_) {
            if (mounted) setState(() => _loading = false);
          },
          onWebResourceError: (error) {
            debugPrint('WebView error: $error');
          },
        ),
      )
      ..loadFile(_file.path);
  }

  Future<void> _exportData(JavaScriptMessage message) async {
    try {
      final data = jsonDecode(message.message) as Map<String, dynamic>;
      final name = data['name'];
      if (name == 'mapbanai-map.png' || name == 'mapbanai-map.jpg') {
        final image = AtlasImageExport.fromMessage(data);
        final saveToFile = data['destination'] == 'save';
        if (saveToFile) {
          final path = await FilePicker.platform.saveFile(
              dialogTitle: 'Save map image',
              fileName: image.name,
              type: FileType.custom,
              allowedExtensions: [
                image.name.endsWith('.png') ? 'png' : 'jpg',
                if (image.name.endsWith('.jpg')) 'jpeg'
              ],
              bytes: image.bytes);
          if (path != null) {
            // Android's picker writes the bytes; desktop pickers return a path.
            if (!Platform.isAndroid && !Platform.isIOS) {
              await File(path).writeAsBytes(image.bytes);
            }
            if (mounted) {
              ScaffoldMessenger.of(context).showSnackBar(
                  const SnackBar(content: Text('Map image saved')));
            }
          }
          return;
        }
        final directory = await getTemporaryDirectory();
        final file = await File('${directory.path}/${image.name}')
            .writeAsBytes(image.bytes);
        await Share.shareXFiles([XFile(file.path, mimeType: image.mimeType)],
            subject: 'MapBanai map image');
        return;
      }
      if (name != 'mapbanai-filtered.geojson' &&
          name != 'mapbanai-filtered.csv') return;
      final content = data['content'];
      if (content is! String) return;
      final directory = await getTemporaryDirectory();
      final file = await File('${directory.path}/$name').writeAsString(content);
      await Share.shareXFiles([XFile(file.path)],
          subject: 'MapBanai filtered data');
    } catch (error) {
      if (mounted) {
        ScaffoldMessenger.of(context)
            .showSnackBar(SnackBar(content: Text('Export failed: $error')));
      }
    }
  }

  Future<void> _chooseProject() async {
    final db = widget.database;
    if (db == null) return;
    final projects = await db.getProjects();
    if (!mounted) return;
    final project = await showDialog<Project>(
        context: context,
        builder: (context) =>
            SimpleDialog(title: const Text('Select project'), children: [
              for (final project in projects)
                SimpleDialogOption(
                    onPressed: () => Navigator.pop(context, project),
                    child: Text(project.name))
            ]));
    if (project == null || !mounted) return;
    try {
      context
          .read<ProjectState>()
          .setSelectedProject(project.name, projectId: project.id);
    } catch (_) {}
    setState(() => _loading = true);
    try {
      final generator = WebMapGenerator(
          dataService: WebMapDataService(db, studyAreaStore: StudyAreaStore()));
      final html = await generator.generateHtml(projectId: project.id);
      _file = await generator.writeToFile(html);
      _projectName = project.name;
      _projectId = project.id;
      await _controller.loadFile(_file.path);
    } catch (error) {
      if (mounted) {
        setState(() => _loading = false);
        ScaffoldMessenger.of(context).showSnackBar(
            SnackBar(content: Text('Cannot open project map: $error')));
      }
    }
  }

  Future<void> _share() async {
    try {
      await Share.shareXFiles(
        [XFile(_file.path)],
        text: 'MapBanai WebMap',
        subject: 'MapBanai WebMap',
      );
    } catch (e) {
      if (mounted) {
        ScaffoldMessenger.of(context).showSnackBar(
          SnackBar(content: Text('Share failed: $e')),
        );
      }
    }
  }

  @override
  Widget build(BuildContext context) {
    return Scaffold(
      appBar: AppBar(
        title: Text(_projectName.isEmpty ? 'Project Atlas' : _projectName),
        actions: [
          if (widget.database != null)
            IconButton(
                onPressed: _chooseProject,
                tooltip: "Select project",
                icon: const Icon(Icons.folder_outlined)),
          IconButton(
            icon: const Icon(Icons.share_outlined),
            tooltip: 'Share HTML file',
            onPressed: _share,
          ),
        ],
      ),
      bottomNavigationBar: SafeArea(
          child: Padding(
              padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 8),
              child: Row(children: [
                Expanded(
                    child: FilledButton.icon(
                        onPressed: _loading ? null : _openStudio,
                        icon: const Icon(Icons.download_outlined),
                        label: const Text('Download Map'))),
                if (widget.database != null && _projectId != null) ...[
                  const SizedBox(width: 8),
                  OutlinedButton.icon(
                      onPressed: _loading ? null : _manageLayers,
                      icon: const Icon(Icons.layers_outlined),
                      label: const Text("Layers")),
                ],
              ]))),
      body: Stack(
        children: [
          WebViewWidget(controller: _controller),
          if (_loading) const Center(child: CircularProgressIndicator()),
        ],
      ),
    );
  }
}
