"""Apply reviewed UI copy from an AST audit and generate ARB-backed lookup.

One-time migration: python tool/localize_ui.py AUDIT_JSON TRANSLATIONS_JSON
For new copy, add messages to the ARB catalogues and regenerate the lookup with
python tool/localize_ui.py --refresh, then run flutter gen-l10n.
Only audited app-owned text expressions are changed; data keys are excluded.
"""
import hashlib
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def literal(value):
    return "'" + value.replace('\\', '\\\\').replace("'", "\\'").replace('$', r'\$').replace('\n', r'\n').replace('\r', r'\r') + "'"


def icu(value):
    # Keep placeholders, but quote literal expression examples such as ${width}.
    value = value.replace("'", "''")
    return re.sub(r'\{([^{}]*)\}', lambda m: m[0] if re.fullmatch(r'v\d+', m[1]) else "'{'" + m[1] + "'}'", value)


def main():
    en_path, bn_path = (ROOT / 'lib/l10n' / f'app_{lang}.arb' for lang in ('en', 'bn'))
    en, bn = (json.loads(p.read_text(encoding='utf-8')) for p in (en_path, bn_path))
    if len(sys.argv) == 3:
        records = json.loads(Path(sys.argv[1]).read_text(encoding='utf-8'))
        translations = json.loads(Path(sys.argv[2]).read_text(encoding='utf-8'))
        edits = defaultdict(dict)
        # Dart offsets count UTF-16 code units, including CRLF. Preserve both.
        originals = {name: (ROOT / name).read_bytes().decode('utf-8')
                     for name in {row['path'] for row in records}}
        for row in records:
            source = originals[row['path']].encode('utf-16-le')
            actual = source[row['start'] * 2:row['end'] * 2].decode('utf-16-le')
            if actual != row['source']:
                raise ValueError(f"Source changed since audit: {row['path']}:{row['start']}")
        backup = Path(sys.argv[1]).parent / 'ui-copy-originals'
        for name, source in originals.items():
            target = backup / name
            target.parent.mkdir(parents=True, exist_ok=True)
            target.write_bytes(source.encode('utf-8'))
        for row in records:
            key = row['key']
            if key not in translations:
                raise ValueError(f'Untranslated UI copy: {key}')
            args = ', [' + ', '.join(row['params']) + ']' if row['params'] else ''
            edits[row['path']][(row['start'], row['end'])] = f'ui(context, {literal(key)}{args})'
            for offset in row['consts']:
                edits[row['path']][(offset, offset + 5)] = ''
        for name, changes in edits.items():
            path = ROOT / name
            source = originals[name].encode('utf-16-le')
            for (start, end), text in sorted(changes.items(), reverse=True):
                source = source[:start * 2] + text.encode('utf-16-le') + source[end * 2:]
            source = source.decode('utf-16-le')
            if "import 'package:mapbanai/l10n/ui_text.dart';" not in source:
                source = "import 'package:mapbanai/l10n/ui_text.dart';\n" + source
            path.write_bytes(source.encode('utf-8'))
        for english, bangla in sorted(translations.items()):
            name = 'ui' + hashlib.sha1(english.encode()).hexdigest()[:12]
            en[name], bn[name] = icu(english), icu(bangla)
            params = re.findall(r'\{(v\d+)\}', english)
            # Only interpolation-generated parameters; raw XLSForm examples stay literal.
            if params:
                en['@' + name] = {'description': english, 'placeholders': {p: {'type': 'String'} for p in dict.fromkeys(params)}}
            else:
                en['@' + name] = {'description': english}
        for path, values in ((en_path, en), (bn_path, bn)):
            path.write_text(json.dumps(values, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
    elif sys.argv[1:] != ['--refresh']:
        raise SystemExit(__doc__)

    lines = [
        '// Generated by tool/localize_ui.py --refresh. Translations live in ARB files.',
        "import 'package:flutter/widgets.dart';",
        "import 'package:mapbanai/l10n/app_localizations.dart';",
        '',
        '/// Localize interface copy and known field captions, leaving record values intact.',
        'String ui(BuildContext context, String message, [List<Object?> args = const []]) {',
        '  final l10n = Localizations.of<AppLocalizations>(context, AppLocalizations) ??',
        "      lookupAppLocalizations(Localizations.maybeLocaleOf(context) ?? const Locale('en'));",
        '  String value(int index) {',
        "    if (index >= args.length) return '';",
        '    final item = args[index];',
        '    if (item is StateError) return ui(context, item.message);',
        '    if (item is FormatException) return ui(context, item.message);',
        "    if (item is ArgumentError) return ui(context, item.message?.toString() ?? item.toString());",
        "    return item?.toString() ?? '';",
        '  }',
        '  switch (message) {',
    ]
    for name, english in en.items():
        if not name.startswith('ui') or not re.fullmatch(r'ui[0-9a-f]{12}', name):
            continue
        metadata = en.get('@' + name, {})
        message = metadata.get('description', english)
        params = metadata.get('placeholders', {})
        call = '(' + ', '.join(f'value({int(p[1:])})' for p in params) + ')' if params else ''
        lines.append(f'    case {literal(message)}: return l10n.{name}{call};')
    lines += [
        '    default:',
        "      for (final prefix in ['Bad state: ', 'FormatException: ']) {",
        '        if (message.startsWith(prefix)) return ui(context, message.substring(prefix.length));',
        '      }',
        '      var result = message;',
        '      for (var i = 0; i < args.length; i++) {',
        "        result = result.replaceAll('{v$i}', value(i));",
        '      }',
        '      return result;',
        '  }',
        '}',
        '',
    ]
    (ROOT / 'lib/l10n/ui_text.dart').write_text('\n'.join(lines), encoding='utf-8')
    # The embedded WebMap shares the same reviewed caption catalogue. It only
    # translates controls; user data and image/poster input values are excluded.
    captions = {}
    for name, metadata in en.items():
        if not name.startswith('@ui') or not isinstance(metadata, dict):
            continue
        message = metadata.get('description', '')
        if metadata.get('placeholders') or not message or len(message) > 180 or '\n' in message:
            continue
        translated = bn.get(name[1:])
        if translated:
            captions[message] = translated.replace("''", "'").replace("'{'", '{').replace("'}'", '}')
    (ROOT / 'assets/webmap/ui_bn.json').write_text(
        json.dumps(captions, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
